package it.universita.esse3.assegnamento;

// A differenza delle variabili locali, i campi hanno un valore di default
public class ValoriDiDefault {
    private int voto;
    private boolean verbalizzato;
    private String matricola;

    public int getVoto() {
        return voto;
    }

    public boolean isVerbalizzato() {
        return verbalizzato;
    }

    public String getMatricola() {
        return matricola;
    }
}
